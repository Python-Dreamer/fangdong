  function t(key, params) {
    var lang = localStorage.getItem('lang') || 'zh-CN';
    var dict = translations[lang] || translations['zh-CN'];
    var text = dict[key];
    if (text === undefined) text = translations['zh-CN'][key] || key;
    if (params) {
      for (var k in params) {
        if (params.hasOwnProperty(k)) {
          text = text.split('{' + k + '}').join(String(params[k]));
        }
      }
    }
    return text;
  }

  function setLang(lang) {
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
    if (window.__rerender) window.__rerender();
  }

  function getLang() {
    return localStorage.getItem('lang') || 'zh-CN';
  }

  function toggleLang() {
    var cur = getLang();
    setLang(cur === 'zh-CN' ? 'en' : 'zh-CN');
  }

  function initDataI18n() {
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute('data-i18n');
      if (key) els[i].textContent = t(key);
    }
  }

  window.i18n = { t: t, setLang: setLang, getLang: getLang, toggleLang: toggleLang, initDataI18n: initDataI18n, translations: translations };
